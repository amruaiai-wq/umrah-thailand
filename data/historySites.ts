export function getSites(cat: CategorySlug): (Site | Battle)[] {
  if (cat === "makkah") return MAKKAH_SITES;
  if (cat === "madinah") return MADINAH_SITES;
  return BATTLES;
}

export function findItem(cat: CategorySlug, slug: string): Site | Battle | null {
  return getSites(cat).find((s) => s.slug === slug) ?? null;
}

export function isBattle(item: Site | Battle): item is Battle {
  return "sides" in item;
}

export function getCategoryMeta(slug: CategorySlug) {
  return HIST_CATEGORIES.find((c) => c.slug === slug)!;
}
